def kit_files(spec: dict) -> dict:
    kits = set(spec.get("kits") or [])
    files: dict[str, str] = {}
    if "inventory" in kits:
        files.update(inventory_files(spec))
    if "invoicing" in kits:
        files.update(invoicing_files(spec))
    if "pos" in kits:
        files.update(pos_files(spec))
    if "booking" in kits:
        files.update(booking_files(spec))
    if "sales" in kits:
        files.update(sales_files(spec))
    if "workflow" in kits:
        files.update(workflow_files(spec))
    if "reports" in kits:
        files.update(reports_files(spec))
    return files
