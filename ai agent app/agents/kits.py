"""
agents/kits.py — deterministic business-behaviour kits (never LLM).

Each kit adds fixed, parameterised TypeScript services + routes that implement the
error-prone server-side logic (atomic stock changes, invoice status derivation,
POS checkout, rental overlap, purchase receiving, sales) that a 12B model cannot
write bug-free. Kits are matched to the spec's data model + declared `kits` list.

The domain models themselves (SparePart, Invoice, …) are generated by the CRUD kit
from the SRS collections; these kits add the shared services + transaction endpoints
that operate on them.
"""
from __future__ import annotations

import json
import re


# ── model resolution (find the right collection by shape) ─────────────────────

def _model_names(spec: dict) -> list[str]:
    return [m.get("name", "") for m in (spec.get("data_model") or [])]


def _has_field(model: dict, name: str) -> bool:
    return any(f.get("name") == name for f in (model.get("fields") or []))


def find_model(spec: dict, *keywords: str, field: str | None = None) -> str | None:
    dm = spec.get("data_model") or []
    for m in dm:
        nm = str(m.get("name", "")).lower()
        if any(k in nm for k in keywords):
            return m["name"]
    if field:
        for m in dm:
            if _has_field(m, field):
                return m["name"]
    return None


# ── Inventory / Stock kit ─────────────────────────────────────────────────────

def _stock_lib(part: str, movement: str) -> str:
    return (
        f"import {part} from '@/models/{part}'\n"
        f"import {movement} from '@/models/{movement}'\n\n"
        "export interface StockChange {\n"
        "  sparePartId: string\n"
        "  quantity: number\n"
        "  movementType: string\n"
        "  direction: 1 | -1\n"
        "  referenceType?: string\n"
        "  referenceId?: string\n"
        "  note?: string\n"
        "  createdBy: string\n"
        "}\n\n"
        "// Atomic-ish stock change: validates non-negative stock, updates quantity, and\n"
        "// always writes a movement record. (Single-node in-memory Mongo has no multi-doc\n"
        "// transactions, so ops are sequential with a pre-check.)\n"
        "export async function adjustStock(c: StockChange): Promise<number> {\n"
        f"  const part: any = await {part}.findById(c.sparePartId)\n"
        "  if (!part) throw new Error('Item not found')\n"
        "  const before = Number(part.quantity || 0)\n"
        "  const after = before + c.direction * Math.abs(c.quantity)\n"
        "  if (after < 0) throw new Error('Insufficient stock')\n"
        "  part.quantity = after\n"
        "  await part.save()\n"
        f"  await {movement}.create({{\n"
        "    sparePartId: c.sparePartId, movementType: c.movementType,\n"
        "    quantity: Math.abs(c.quantity), quantityBefore: before, quantityAfter: after,\n"
        "    referenceType: c.referenceType || 'manual', referenceId: c.referenceId,\n"
        "    note: c.note, createdBy: c.createdBy,\n"
        "  })\n"
        "  return after\n"
        "}\n"
    )


_STOCK_ADJUST_ROUTE = (
    "import { NextRequest, NextResponse } from 'next/server'\n"
    "import dbConnect from '@/lib/mongodb'\n"
    "import { adjustStock } from '@/lib/stock'\n"
    "import { getSession } from '@/lib/auth'\n\n"
    "export const dynamic = 'force-dynamic'\n\n"
    "export async function POST(req: NextRequest) {\n"
    "  try {\n"
    "    const session = await getSession()\n"
    "    if (!session) return NextResponse.json({ error: 'Unauthorized' }, { status: 401 })\n"
    "    await dbConnect()\n"
    "    const body = await req.json()\n"
    "    const dir = body.direction === 'out' ? -1 : 1\n"
    "    const after = await adjustStock({\n"
    "      sparePartId: body.sparePartId, quantity: Number(body.quantity),\n"
    "      movementType: dir > 0 ? 'adjustment_in' : 'adjustment_out',\n"
    "      referenceType: 'manual', createdBy: session.userId, direction: dir as 1 | -1,\n"
    "    })\n"
    "    return NextResponse.json({ success: true, quantity: after })\n"
    "  } catch (e: any) {\n"
    "    return NextResponse.json({ error: e?.message || 'error' }, { status: 400 })\n"
    "  }\n"
    "}\n"
)


def inventory_files(spec: dict) -> dict:
    part = find_model(spec, "sparepart", "part", "product", "item", field="reorderLevel") \
        or find_model(spec, "sparepart", "part", "product", field="quantity")
    movement = find_model(spec, "stockmovement", "movement")
    if not part or not movement:
        return {}
    return {
        "lib/stock.ts": _stock_lib(part, movement),
        "app/api/stock/adjust/route.ts": _STOCK_ADJUST_ROUTE,
    }


# ── Invoicing / Payments kit ──────────────────────────────────────────────────

def _invoicing_lib(invoice: str, payment: str) -> str:
    return (
        f"import {invoice} from '@/models/{invoice}'\n"
        f"import {payment} from '@/models/{payment}'\n\n"
        "export function invoiceStatus(total: number, paid: number): string {\n"
        "  if (paid <= 0) return 'unpaid'\n"
        "  if (paid >= total) return 'paid'\n"
        "  return 'partial'\n"
        "}\n\n"
        "export async function createInvoice(input: {\n"
        "  invoiceType: string; referenceId: string; customerId?: string;\n"
        "  subtotal: number; discount?: number; total: number;\n"
        "}) {\n"
        "  const discount = Number(input.discount || 0)\n"
        "  const total = Number(input.total)\n"
        f"  const inv = await {invoice}.create({{\n"
        "    invoiceNo: 'INV-' + Date.now(),\n"
        "    invoiceType: input.invoiceType, referenceId: input.referenceId,\n"
        "    customerId: input.customerId, subtotal: Number(input.subtotal),\n"
        "    discount, total, paidAmount: 0, balance: total, status: 'unpaid',\n"
        "    issuedAt: new Date(),\n"
        "  })\n"
        "  return inv\n"
        "}\n\n"
        "// Record a payment against an invoice. Server-side: amount>0, cannot exceed balance,\n"
        "// status recalculated. Never trusts client totals.\n"
        "export async function recordPayment(invoiceId: string, p: {\n"
        "  amount: number; method: string; reference?: string; receivedBy: string;\n"
        "}) {\n"
        f"  const inv: any = await {invoice}.findById(invoiceId)\n"
        "  if (!inv) throw new Error('Invoice not found')\n"
        "  const amount = Number(p.amount)\n"
        "  if (!(amount > 0)) throw new Error('Payment must be greater than zero')\n"
        "  const total = Number(inv.total || 0)\n"
        "  const newPaid = Number(inv.paidAmount || 0) + amount\n"
        "  if (newPaid > total) throw new Error('Payment exceeds invoice balance')\n"
        "  inv.paidAmount = newPaid\n"
        "  inv.balance = total - newPaid\n"
        "  inv.status = invoiceStatus(total, newPaid)\n"
        "  await inv.save()\n"
        f"  await {payment}.create({{\n"
        "    paymentNo: 'PAY-' + Date.now(), invoiceId, amount, method: p.method,\n"
        "    reference: p.reference, paidAt: new Date(), receivedBy: p.receivedBy,\n"
        "  })\n"
        "  return inv\n"
        "}\n"
    )


