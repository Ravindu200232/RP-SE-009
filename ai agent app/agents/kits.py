# ── Workflow (job cards) kit ──────────────────────────────────────────────────

def workflow_files(spec: dict) -> dict:
    job = find_model(spec, "jobcard", "workorder", "ticket")
    part = find_model(spec, "sparepart", "part", "product", field="reorderLevel")
    if not job:
        return {}
    seg = _seg(job)
    stock_import = "import { adjustStock } from '@/lib/stock'\n" if part else ""
    stock_block = (
        "      if (item.itemType === 'spare_part' && item.sparePartId) {\n"
        "        await adjustStock({ sparePartId: String(item.sparePartId), quantity: Number(item.quantity || 1), movementType: 'service_usage', direction: -1, referenceType: 'job_card', referenceId: id, createdBy: session.userId })\n"
        "      }\n" if part else "")
    route = (
        "import { NextRequest, NextResponse } from 'next/server'\n"
        "import dbConnect from '@/lib/mongodb'\n"
        f"import {job} from '@/models/{job}'\n"
        f"{stock_import}"
        "import { getSession } from '@/lib/auth'\n\n"
        "export const dynamic = 'force-dynamic'\n\n"
        "export async function POST(req: NextRequest, { params }: { params: Promise<{ id: string }> }) {\n"
        "  try {\n"
        "    const { id } = await params\n"
        "    const session = await getSession()\n"
        "    if (!session) return NextResponse.json({ error: 'Unauthorized' }, { status: 401 })\n"
        "    await dbConnect()\n"
        f"    const card: any = await {job}.findById(id)\n"
        "    if (!card) return NextResponse.json({ error: 'Not found' }, { status: 404 })\n"
        "    const item = await req.json()\n"
        "    const quantity = Number(item.quantity || 1)\n"
        "    const unitPrice = Number(item.unitPrice || 0)\n"
        "    const lineTotal = quantity * unitPrice\n"
        f"{stock_block}"
        "    card.items = [...(card.items || []), { ...item, quantity, unitPrice, lineTotal }]\n"
        "    const labor = (card.items || []).filter((i: any) => i.itemType === 'labor').reduce((s: number, i: any) => s + Number(i.lineTotal || 0), 0)\n"
        "    const parts = (card.items || []).filter((i: any) => i.itemType === 'spare_part').reduce((s: number, i: any) => s + Number(i.lineTotal || 0), 0)\n"
        "    card.laborTotal = labor; card.partsTotal = parts; card.grandTotal = labor + parts\n"
        "    await card.save()\n"
        "    return NextResponse.json({ success: true, data: card })\n"
        "  } catch (e: any) {\n"
        "    return NextResponse.json({ error: e?.message || 'error' }, { status: 400 })\n"
        "  }\n"
        "}\n"
    )
    return {f"app/api/{seg}/[id]/items/route.ts": route}


