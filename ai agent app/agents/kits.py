# ── field helpers ─────────────────────────────────────────────────────────────

def _get_model(spec: dict, name: str) -> dict | None:
    return next((m for m in (spec.get("data_model") or []) if m.get("name") == name), None)


def find_field(model: dict | None, *names: str, ref: str | None = None,
               default: str | None = None) -> str | None:
    if not model:
        return default
    fields = model.get("fields") or []
    if ref:
        for f in fields:
            if f.get("ref") == ref:
                return f["name"]
    for f in fields:
        fn = str(f.get("name", "")).lower()
        if any(n in fn for n in names):
            return f["name"]
    return default


def _seg(name: str) -> str:
    from agents.scaffold import route_name
    return route_name(name)


# ── POS kit ───────────────────────────────────────────────────────────────────

def pos_files(spec: dict) -> dict:
    pos = find_model(spec, "possale", "pos")
    part = find_model(spec, "sparepart", "part", "product", field="reorderLevel") \
        or find_model(spec, "part", "product", field="quantity")
    has_invoicing = bool(find_model(spec, "invoice"))
    if not pos or not part:
        return {}
    inv_import = "import { createInvoice } from '@/lib/invoicing'\n" if has_invoicing else ""
    inv_block = (
        "    const invoice = await createInvoice({ invoiceType: 'pos', referenceId: String(sale._id), "
        "customerId: body.customerId, subtotal, discount, total })\n"
        "    invoice.paidAmount = total; invoice.balance = 0; invoice.status = 'paid'; await invoice.save()\n"
        "    return NextResponse.json({ success: true, data: { sale, invoice } })\n"
        if has_invoicing else
        "    return NextResponse.json({ success: true, data: { sale } })\n"
    )
    route = (
        "import { NextRequest, NextResponse } from 'next/server'\n"
        "import dbConnect from '@/lib/mongodb'\n"
        f"import {pos} from '@/models/{pos}'\n"
        f"import {part} from '@/models/{part}'\n"
        "import { adjustStock } from '@/lib/stock'\n"
        f"{inv_import}"
        "import { getSession } from '@/lib/auth'\n\n"
        "export const dynamic = 'force-dynamic'\n\n"
        "export async function POST(req: NextRequest) {\n"
        "  try {\n"
        "    const session = await getSession()\n"
        "    if (!session) return NextResponse.json({ error: 'Unauthorized' }, { status: 401 })\n"
        "    await dbConnect()\n"
        "    const body = await req.json()\n"
        "    const items = Array.isArray(body.items) ? body.items : []\n"
        "    if (items.length === 0) throw new Error('Cart is empty')\n"
        "    const lineItems: any[] = []\n"
        "    let subtotal = 0\n"
        "    for (const it of items) {\n"
        f"      const p: any = await {part}.findById(it.sparePartId)\n"
        "      if (!p) throw new Error('Item not found')\n"
        "      const qty = Number(it.quantity)\n"
        "      if (!(qty >= 1)) throw new Error('Invalid quantity')\n"
        "      if (Number(p.quantity || 0) < qty) throw new Error('Insufficient stock for ' + p.name)\n"
        "      const unitPrice = Number(p.sellingPrice || 0)\n"
        "      const discount = Number(it.discount || 0)\n"
        "      const lineTotal = unitPrice * qty - discount\n"
        "      subtotal += lineTotal\n"
        "      lineItems.push({ sparePartId: p._id, partCode: p.partCode, name: p.name, quantity: qty, unitPrice, discount, lineTotal })\n"
        "    }\n"
        "    const discount = Number(body.discount || 0)\n"
        "    const total = subtotal - discount\n"
        "    for (const li of lineItems) {\n"
        "      await adjustStock({ sparePartId: String(li.sparePartId), quantity: li.quantity, movementType: 'pos_sale', direction: -1, referenceType: 'pos_sale', createdBy: session.userId })\n"
        "    }\n"
        f"    const sale = await {pos}.create({{ receiptNo: 'POS-' + Date.now(), customerId: body.customerId, items: lineItems, subtotal, discount, total, paymentMethod: body.paymentMethod || 'cash', paymentStatus: 'paid', createdBy: session.userId }})\n"
        f"{inv_block}"
        "  } catch (e: any) {\n"
        "    return NextResponse.json({ error: e?.message || 'error' }, { status: 400 })\n"
        "  }\n"
        "}\n"
    )
    return {"app/api/pos/checkout/route.ts": route}


# ── Booking / Rental kit ──────────────────────────────────────────────────────

def booking_files(spec: dict) -> dict:
    rental = find_model(spec, "rental", "booking")
    vehicle = find_model(spec, "vehicle", "room", "resource", "asset")
    if not rental:
        return {}
    rm = _get_model(spec, rental)
    veh_field = find_field(rm, "vehicle", "room", "resource", "asset", ref=vehicle, default="vehicleId")
    # Detect the two date fields by TYPE (first = pickup/start, second = return/end) —
    # robust against ambiguous names (a "customer" field would falsely match "to").
    date_fields = [f["name"] for f in (rm.get("fields") or []) if str(f.get("type")) == "Date"]
    pickup = date_fields[0] if len(date_fields) >= 1 else "pickupAt"
    ret = date_fields[1] if len(date_fields) >= 2 else "returnAt"
    rate = find_field(rm, "dailyrate", "rate", default="dailyRate")
    fields = rm.get("fields") or []
    # Identifier (unique String) — auto-generate if the client omits it.
    id_field = next((f["name"] for f in fields if f.get("unique") and str(f.get("type")) == "String"), None)
    id_prefix = (re.sub(r"[^A-Za-z]", "", id_field)[:3].upper() if id_field else "BK") or "BK"
    # Optional derived fields — only set them if the model actually has them.
    days_field = next((f["name"] for f in fields if "day" in f["name"].lower() and str(f.get("type")) == "Number"), None)
    total_field = next((f["name"] for f in fields if f["name"].lower() in ("total", "grandtotal", "amount") and str(f.get("type")) == "Number"), None)
    status_enum = next((f.get("enum") for f in fields if f["name"] == "status"), None) or []
    _active = {"confirmed", "picked_up", "checked_in", "active", "booked", "borrowed", "reserved", "in_progress"}
    overlap = [s for s in status_enum if s in _active] or (["confirmed"] if not status_enum else [status_enum[0]])
    default_status = next((s for s in ["confirmed", "booked", "reserved", "requested"] if s in status_enum),
                          status_enum[0] if status_enum else "confirmed")
    overlap_ts = "[" + ", ".join(f"'{s}'" for s in overlap) + "]"
    create_parts = ["...body", f"{veh_field}: vehicleId", f"status: body.status || '{default_status}'"]
    if id_field:
        create_parts.append(f"{id_field}: body.{id_field} || '{id_prefix}-' + Date.now()")
    if days_field:
        create_parts.append(f"{days_field}: days")
    if total_field:
        create_parts.append(f"{total_field}: dailyRate * days")
    create_obj = "{ " + ", ".join(create_parts) + " }"
    seg = _seg(rental)
    route = (
        "import { NextRequest, NextResponse } from 'next/server'\n"
        "import dbConnect from '@/lib/mongodb'\n"
        f"import {rental} from '@/models/{rental}'\n"
        "import { ok, serverError } from '@/lib/api'\n"
        "import { getSession } from '@/lib/auth'\n\n"
        "export const dynamic = 'force-dynamic'\n\n"
        "export async function GET() {\n"
        "  try {\n"
        "    await dbConnect()\n"
        f"    const items = await {rental}.find({{}}).sort({{ createdAt: -1 }}).lean()\n"
        "    return ok(items)\n"
        "  } catch (e) { return serverError(e) }\n"
        "}\n\n"
        "export async function POST(req: NextRequest) {\n"
        "  try {\n"
        "    const session = await getSession()\n"
        "    if (!session) return NextResponse.json({ error: 'Unauthorized' }, { status: 401 })\n"
        "    await dbConnect()\n"
        "    const body = await req.json()\n"
        f"    const vehicleId = body.{veh_field}\n"
        f"    const pickup = new Date(body.{pickup})\n"
        f"    const ret = new Date(body.{ret})\n"
        "    if (isNaN(pickup.getTime()) || isNaN(ret.getTime())) throw new Error('Pickup and return dates are required')\n"
        "    if (ret <= pickup) throw new Error('Return date must be after pickup date')\n"
        "    // overlap: no active booking for this resource intersecting the range\n"
        f"    const clash = await {rental}.findOne({{\n"
        f"      {veh_field}: vehicleId, status: {{ $in: {overlap_ts} }},\n"
        f"      {pickup}: {{ $lt: ret }}, {ret}: {{ $gt: pickup }},\n"
        "    })\n"
        "    if (clash) return NextResponse.json({ error: 'Already booked for those dates' }, { status: 409 })\n"
        "    const days = Math.max(1, Math.ceil((ret.getTime() - pickup.getTime()) / 86400000))\n"
        f"    const dailyRate = Number(body.{rate} || 0)\n"
        f"    const item = await {rental}.create({create_obj})\n"
        "    return NextResponse.json({ success: true, data: item }, { status: 201 })\n"
        "  } catch (e: any) {\n"
        "    return NextResponse.json({ error: e?.message || 'error' }, { status: 400 })\n"
        "  }\n"
        "}\n"
    )
    return {f"app/api/{seg}/route.ts": route}


