    counts = ",\n".join(f"      {json.dumps(_seg(m['name']))}: await {m['name']}.countDocuments()"
                        for m in dm)
    revenue = (f"    const paid = await {invoice}.find({{ status: 'paid' }}).lean()\n"
               f"    const revenue = paid.reduce((s: number, i: any) => s + Number(i.total || 0), 0)\n"
               if invoice else "    const revenue = 0\n")
    low = (f"    const lowStock = await {part}.countDocuments({{ $expr: {{ $lte: ['$quantity', '$reorderLevel'] }} }})\n"
           if part else "    const lowStock = 0\n")
    summary = (
        "import { NextResponse } from 'next/server'\n"
        "import dbConnect from '@/lib/mongodb'\n"
        f"{imports}"
        "import { getSession } from '@/lib/auth'\n\n"
        "export const dynamic = 'force-dynamic'\n\n"
        "export async function GET() {\n"
        "  try {\n"
        "    const session = await getSession()\n"
        "    if (!session) return NextResponse.json({ error: 'Unauthorized' }, { status: 401 })\n"
        "    await dbConnect()\n"
        "    const counts: Record<string, number> = {\n"
        f"{counts},\n"
        "    }\n"
        f"{revenue}"
        f"{low}"
        "    return NextResponse.json({ success: true, data: { counts, revenue, lowStock } })\n"
        "  } catch (e: any) {\n"
        "    return NextResponse.json({ error: e?.message || 'error' }, { status: 500 })\n"
        "  }\n"
        "}\n"
    )
    type_map: dict[str, str] = {}
    for m in dm:
        nm = m["name"].lower()
        if "possale" in nm or ("pos" in nm and "sale" in nm):
            type_map["pos"] = m["name"]
        elif "sale" in nm:
            type_map["sales"] = m["name"]
        elif "rental" in nm or "booking" in nm:
            type_map["rentals"] = m["name"]
        elif "invoice" in nm:
            type_map["invoices"] = m["name"]
    type_imports = "".join(f"import {v} from '@/models/{v}'\n" for v in dict.fromkeys(type_map.values()))
    cases = "\n".join(
        f"    if (type === '{k}') {{ const rows = await {v}.find(range).sort({{ createdAt: -1 }}).lean(); "
        f"const total = rows.reduce((s: number, r: any) => s + Number(r.total || 0), 0); "
        f"return NextResponse.json({{ success: true, data: {{ rows, total, count: rows.length }} }}) }}"
        for k, v in type_map.items()
    )
    reports = (
        "import { NextRequest, NextResponse } from 'next/server'\n"
        "import dbConnect from '@/lib/mongodb'\n"
        f"{type_imports}"
        "import { getSession } from '@/lib/auth'\n\n"
        "export const dynamic = 'force-dynamic'\n\n"
        "export async function GET(req: NextRequest) {\n"
        "  try {\n"
        "    const session = await getSession()\n"
        "    if (!session) return NextResponse.json({ error: 'Unauthorized' }, { status: 401 })\n"
        "    await dbConnect()\n"
        "    const { searchParams } = new URL(req.url)\n"
        "    const type = searchParams.get('type') || ''\n"
        "    const from = searchParams.get('from'); const to = searchParams.get('to')\n"
        "    const range: any = {}\n"
        "    if (from || to) { range.createdAt = {}; if (from) range.createdAt.$gte = new Date(from); if (to) range.createdAt.$lte = new Date(to) }\n"
        f"{cases}\n"
        "    return NextResponse.json({ success: true, data: { rows: [], total: 0, count: 0 } })\n"
        "  } catch (e: any) {\n"
        "    return NextResponse.json({ error: e?.message || 'error' }, { status: 500 })\n"
        "  }\n"
        "}\n"
    )
    return {
        "app/api/dashboard/summary/route.ts": summary,
        "app/api/reports/route.ts": reports,
    }


