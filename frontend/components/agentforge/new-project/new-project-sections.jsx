function ProgressStagePanel({ label, statuses, duration = 5, color = "#1f6feb", onComplete }) {
  const [progress, setProgress] = useState(0);
  const [statusIndex, setStatusIndex] = useState(0);

  useEffect(() => {
    const tickCount = duration * 10;
    const progressInterval = setInterval(() => {
      setProgress((current) => {
        const next = current + 100 / tickCount;
        if (next >= 100) {
          clearInterval(progressInterval);
          setTimeout(() => onComplete?.(), 300);
          return 100;
        }
        return next;
      });
    }, 100);

    const statusInterval = setInterval(() => {
      setStatusIndex((current) => Math.min(current + 1, statuses.length - 1));
    }, (duration * 1000) / Math.max(statuses.length, 1));

    return () => {
      clearInterval(progressInterval);
      clearInterval(statusInterval);
    };
  }, [color, duration, onComplete, statuses]);

  return (
    <div className="flex w-full max-w-md flex-col items-center gap-4">
      <div className="relative flex min-h-[140px] items-center justify-center">
        <Icon name="Loader2" size={140} className="animate-spin text-[#1f6feb]" />
      </div>
      <p className="text-sm font-medium text-gray-800">{label}</p>
      <p className="min-h-4 text-xs text-gray-500">{statuses[statusIndex]}</p>
      <div className="h-1.5 w-full overflow-hidden rounded-full bg-gray-200">
        <div
          className="h-full rounded-full transition-all duration-100"
          style={{ width: `${progress}%`, background: color }}
        />
      </div>
      <p className="text-xs font-mono" style={{ color }}>
        {Math.round(progress)}%
      </p>
    </div>
  );
}

function ChatBubble({ text, isAgent = true, delay = 0 }) {
  const [visible, setVisible] = useState(false);

  useEffect(() => {
    const timer = setTimeout(() => setVisible(true), delay);
    return () => clearTimeout(timer);
  }, [delay]);

  if (!visible) {
    return null;
  }

  return (
    <div
      className={`flex gap-3 ${isAgent ? "justify-start" : "justify-end"}`}
      style={{ animation: "slideInUp 0.35s ease forwards" }}
    >
      {isAgent ? (
        <div className="mt-1 flex h-7 w-7 flex-shrink-0 items-center justify-center rounded-full bg-[#1f6feb]">
          <Icon name="Zap" size={12} className="text-white" />
        </div>
      ) : null}
      <div
        className={`max-w-[38rem] rounded-2xl px-4 py-2.5 text-sm leading-relaxed ${
          isAgent
            ? "rounded-tl-sm border border-gray-200 bg-white text-gray-800 shadow-sm"
            : "rounded-tr-sm bg-[#1f6feb] text-white"
        }`}
      >
        {text}
      </div>
    </div>
  );
}

function hasAnswerValue(value) {
  return Array.isArray(value) ? value.length > 0 : Boolean(String(value || "").trim());
}

function formatAnswerText(value) {
  if (Array.isArray(value)) {
    return value.join(", ");
  }
  return String(value || "").trim();
}

function normalizeDraftValue(question, value) {
  if (!question) {
    return "";
  }
  if (question.inputType === "multiselect") {
    return Array.isArray(value) ? value : [];
  }
  return value || "";
}

function QuestionComposer({ question, value, onChange, onSubmit }) {
  const normalizedValue = normalizeDraftValue(question, value);
  const hasValue = hasAnswerValue(normalizedValue);

  if (!question) {
    return null;
  }

  if (question.inputType === "select" || question.inputType === "multiselect") {
    const selectedValues = Array.isArray(normalizedValue) ? normalizedValue : [normalizedValue].filter(Boolean);

    return (
      <div
        className="ml-10 rounded-2xl border border-gray-200 bg-white p-4 shadow-sm"
        style={{ animation: "fadeIn 0.3s ease both" }}
      >
        <div className="flex flex-wrap gap-2">
          {(question.options || []).map((option) => {
            const active = selectedValues.includes(option);
            return (
              <button
                key={option}
                type="button"
                onClick={() => {
                  if (question.inputType === "multiselect") {
                    onChange(
                      active ? selectedValues.filter((item) => item !== option) : [...selectedValues, option]
                    );
                    return;
                  }
                  onChange(option);
                }}
                className={`rounded-xl border px-3 py-2 text-xs font-medium transition-all ${
                  active
                    ? "border-[#1f6feb] bg-blue-50 text-[#1f6feb]"
                    : "border-gray-200 bg-white text-gray-600 hover:border-[#1f6feb] hover:bg-blue-50 hover:text-[#1f6feb]"
                }`}
              >
                {option}
              </button>
            );
          })}
        </div>

        <div className="mt-4 flex items-center justify-end">
          <button
            type="button"
            onClick={() => onSubmit(normalizedValue)}
            disabled={!hasValue}
            className={`inline-flex items-center gap-2 rounded-full px-4 py-2 text-xs font-semibold transition-all ${
              hasValue
                ? "bg-[#1f6feb] text-white shadow-[0_10px_28px_-14px_rgba(31,111,235,0.75)]"
                : "bg-gray-100 text-gray-400"
            }`}
          >
            <Icon name="Send" size={13} />
            Save Answer
          </button>
        </div>
      </div>
    );
  }

  const isLongForm = question.inputType === "textarea";

  return (
    <div
      className="ml-10 rounded-2xl border border-gray-200 bg-white p-4 shadow-sm"
      style={{ animation: "fadeIn 0.3s ease both" }}
    >
      {isLongForm ? (
        <textarea
          value={normalizedValue}
          onChange={(event) => onChange(event.target.value)}
          placeholder={question.placeholder || "Write your answer..."}
          rows={5}
          className="w-full resize-none rounded-2xl border border-gray-200 bg-gray-50 px-4 py-3 text-sm text-gray-700 placeholder-gray-400 focus:border-[#1f6feb] focus:bg-white focus:outline-none"
        />
      ) : (
        <input
          value={normalizedValue}
          onChange={(event) => onChange(event.target.value)}
          placeholder={question.placeholder || "Write your answer..."}
          className="w-full rounded-2xl border border-gray-200 bg-gray-50 px-4 py-3 text-sm text-gray-700 placeholder-gray-400 focus:border-[#1f6feb] focus:bg-white focus:outline-none"
        />
      )}

      <div className="mt-4 flex items-center justify-end">
        <button
          type="button"
          onClick={() => onSubmit(normalizedValue)}
          disabled={!hasValue}
          className={`inline-flex items-center gap-2 rounded-full px-4 py-2 text-xs font-semibold transition-all ${
            hasValue
              ? "bg-[#1f6feb] text-white shadow-[0_10px_28px_-14px_rgba(31,111,235,0.75)]"
              : "bg-gray-100 text-gray-400"
          }`}
        >
          <Icon name="Send" size={13} />
          Save Answer
        </button>
      </div>
    </div>
  );
}

