export function QuestioningStage({
  chatRef,
  questions = [],
  currentQ = 0,
  answers = {},
  draftAnswer,
  onDraftAnswerChange,
  onAnswer,
  analysisSummary = "",
  onReset,
  onGenerate,
  isGenerating = false,
  canGenerate = false,
}) {
  const totalQuestions = questions.length;
  const answeredQuestions = questions.filter((question) => hasAnswerValue(answers[question.key])).length;
  const remainingQuestions = Math.max(totalQuestions - answeredQuestions, 0);
  const activeQuestion = currentQ < totalQuestions ? questions[currentQ] : null;

  return (
    <div className="flex flex-1 flex-col overflow-hidden">
      <div className="flex items-center justify-between gap-4 border-b border-gray-200 bg-white/80 px-5 py-4 backdrop-blur flex-shrink-0">
        <div className="flex items-center gap-3">
          <div className="h-2 w-2 rounded-full bg-[#1f6feb] animate-pulse" />
          <div>
            <p className="text-xs font-semibold text-gray-700">Agent 1 - IEEE Requirement Gathering</p>
            <p className="text-[11px] text-gray-400">Short, user-friendly questions. No technical knowledge needed.</p>
          </div>
        </div>
        <div className="flex items-center gap-2">
          <span className="text-xs text-gray-500">
            {Math.min(answeredQuestions + (activeQuestion ? 1 : 0), totalQuestions || 1)} / {totalQuestions || 0} questions
          </span>
          <div className="h-1 w-24 overflow-hidden rounded-full bg-gray-200">
            <div
              className="h-full rounded-full bg-[#1f6feb] transition-all duration-500"
              style={{ width: `${totalQuestions ? (answeredQuestions / totalQuestions) * 100 : 0}%` }}
            />
          </div>
        </div>
      </div>

      <div ref={chatRef} className="flex-1 overflow-y-auto space-y-4 bg-[linear-gradient(180deg,#f8fbff_0%,#ffffff_28%,#ffffff_100%)] px-6 py-6">
        <ChatBubble
          delay={0}
          text={
            analysisSummary
              ? `${analysisSummary} No technical knowledge is needed. I will ask ${totalQuestions || 0} short questions so I can complete the missing SRS details.`
              : `I reviewed your project context. No technical knowledge is needed. I will ask ${totalQuestions || 0} short questions so I can complete the SRS clearly.`
          }
        />

        {questions.map((question, index) => {
          const answerValue = answers[question.key];
          const isAnswered = hasAnswerValue(answerValue);
          const isCurrent = index === currentQ && !isAnswered;
          const showQuestion = isAnswered || isCurrent || index < currentQ;

          if (!showQuestion) {
            return null;
          }

          return (
            <div key={question.key} className="space-y-3">
              <div className="flex gap-3" style={{ animation: "slideInUp 0.35s ease forwards" }}>
                <div className="mt-1 flex h-7 w-7 flex-shrink-0 items-center justify-center rounded-full bg-[#1f6feb]">
                  <Icon name="Zap" size={12} className="text-white" />
                </div>
                <div className="max-w-[38rem] rounded-2xl rounded-tl-sm border border-gray-200 bg-white px-4 py-3 shadow-sm">
                  <p className="mb-1 text-[10px] uppercase tracking-[0.16em] text-gray-400">
                    Question {index + 1} of {totalQuestions}
                  </p>
                  <p className="text-sm leading-relaxed text-gray-800">{question.question}</p>
                </div>
              </div>

              {isAnswered ? <ChatBubble text={formatAnswerText(answerValue)} isAgent={false} /> : null}

              {isCurrent ? (
                <QuestionComposer
                  question={question}
                  value={draftAnswer}
                  onChange={onDraftAnswerChange}
                  onSubmit={onAnswer}
                />
              ) : null}
            </div>
          );
        })}

        {!activeQuestion && totalQuestions > 0 ? (
          <ChatBubble text="Thanks. I now have the answers I need from this interview. Click Build App when you are ready." />
        ) : null}
      </div>

      <div className="flex items-center justify-between gap-3 border-t border-gray-200 bg-white px-5 py-4 flex-shrink-0">
        <button
          type="button"
          onClick={onReset}
          className="inline-flex items-center gap-2 rounded-full border border-gray-200 px-4 py-2 text-xs font-medium text-gray-600 transition-colors hover:border-gray-300 hover:text-gray-900"
        >
          <Icon name="RotateCcw" size={13} />
          Reset
        </button>

        <button
          type="button"
          onClick={onGenerate}
          disabled={isGenerating || !canGenerate}
          className={`inline-flex items-center gap-2 rounded-full px-4 py-2 text-xs font-semibold transition-all ${
            isGenerating || !canGenerate
              ? "bg-gray-100 text-gray-400"
              : "bg-[#1f6feb] text-white shadow-[0_10px_28px_-14px_rgba(31,111,235,0.75)]"
          }`}
        >
          <Icon name="FileOutput" size={13} />
          {isGenerating ? "Building..." : "Build App"}
        </button>
      </div>

      {!canGenerate && totalQuestions > 0 ? (
        <div className="border-t border-gray-100 bg-gray-50 px-5 py-3 text-xs text-gray-500">
          {remainingQuestions} more answer{remainingQuestions === 1 ? "" : "s"} needed before Build App can start.
        </div>
      ) : null}
    </div>
  );
}

